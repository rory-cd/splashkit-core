void CSharpTranslator::translateASTSet(
    const std::vector<CustomAST> &ASTs,
    const fs::path &outputDir,
    const std::string &projectName)
{
    // Ensure output directory exists
    fs::create_directories(outputDir);

    writeProjectFiles(outputDir, projectName);

    // Translate each AST in the list
    for (auto &AST : ASTs)
    {
        std::string filename = AST.filename + ".cs";
        fs::path outputFilepath = outputDir / filename;
        translateAST(AST, projectName, outputFilepath);
    }
}

